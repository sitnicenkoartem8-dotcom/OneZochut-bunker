const eventWeights = { common: 70, rare: 20, epic: 8, legendary: 2 };

function weightedEventPick(events) {
  const total = events.reduce((sum, event) => sum + (eventWeights[event.rarity] || 1), 0);
  let roll = Math.random() * total;
  for (const event of events) {
    roll -= eventWeights[event.rarity] || 1;
    if (roll <= 0) return event;
  }
  return events[0];
}

export function generateStory() {
  const start = pick(apocalypseStarts);
  const place = pick(bunkerPlaces);
  const problem = pick(bunkerProblems);
  const goal = pick(winConditions);
  return {
    title: start[0],
    intro: start[1],
    outside: start[2],
    place,
    problem,
    goal,
    text: `${start[0]}. ${start[1]} Почему нужно прятаться: ${start[2]} Бункер находится ${place}. Главная проблема бункера: ${problem}. Цель выживших: ${goal}.`
  };
}

export function generateBunker(settings = {}) {
  const base = pick(bunkerSizes);
  const [minCap, maxCap] = base[2];
  const capacity = Number(settings.bunkerSeats) || randomInt(minCap, maxCap);
  const maxPlayers = Number(settings.maxPlayers) || Math.max(capacity + 2, 8);
  const roomCount = Math.min(8, randomInt(4, 7));
  const rooms = Array.from({ length: roomCount }, () => pick(bunkerRooms));
  const items = Array.from({ length: randomInt(5, 8) }, () => pick(bunkerItems));
  const defects = Array.from({ length: randomInt(2, 4) }, () => pick(bunkerProblems));
  return {
    title: `${base[0]} бункер на ${capacity} мест`,
    size: base[0],
    description: base[1],
    capacity,
    maxPlayers,
    rooms: [...new Set(rooms)],
    items: [...new Set(items)],
    defects: [...new Set(defects)],
    text: `${base[0]} бункер. Вместимость: ${capacity}/${maxPlayers}. ${base[1]}. Комнаты: ${[...new Set(rooms)].join(", ")}. Предметы: ${[...new Set(items)].join(", ")}. Проблемы: ${[...new Set(defects)].join(", ")}.`
  };
}

export function generateRoundEvent(round = 1, mode = "meme") {
  let available = roundEvents;
  if (mode === "normal") available = roundEvents.filter((event) => event.rarity !== "legendary");
  if (mode === "chaos") available = roundEvents.concat(roundEvents.filter((event) => ["epic", "legendary"].includes(event.rarity)));
  const event = weightedEventPick(available);
  return {
    ...event,
    id: `${event.effectType}_${Date.now()}_${Math.random().toString(16).slice(2, 7)}`,
    round,
    text: `Круг ${round}: ${event.title}. ${event.description} ${event.impact}`
  };
}
