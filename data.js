function randomInt(min, max) {
  return Math.floor(Math.random() * (max - min + 1)) + min;
}

function pick(list) {
  return list[Math.floor(Math.random() * list.length)];
}

function weightedPick(items) {
  const total = items.reduce((sum, item) => sum + item.weight, 0);
  let roll = Math.random() * total;
  for (const item of items) {
    roll -= item.weight;
    if (roll <= 0) return item;
  }
  return items[items.length - 1];
}

function ageStatus(age, race) {
  if (age >= race.young[0] && age <= race.young[1]) return "по меркам этой расы ты молодой";
  if (age >= race.adult[0] && age <= race.adult[1]) return "по меркам этой расы ты в зрелом/сильном возрасте";
  return "по меркам этой расы ты старый и опытный";
}

function saintPhase() {
  const seraphim = Math.random() < 0.05;
  if (seraphim) return ["Серафим", "Шесть крыльев, множество глаз, слабое влияние на материю. Очень редкая форма, но с откатом реальности."];
  const archangel = Math.random() < 0.15;
  if (archangel) return ["Архангел", "Сильные крылья и несколько баффов: скорость, сила, лечение и защита."];
  return ["Ангел", "Базовая форма: маленькие крылья, лёгкая регенерация, скорость и устойчивость к страху."];
}

export function createRaceCard() {
  const race = weightedPick(raceDefinitions);

  if (race.id === "created") {
    const bioAge = randomInt(18, 80);
    const realAge = randomInt(120, 2000);
    return {
      type: "Раса и возраст",
      title: `${race.name}: ${realAge} лет / тело ${bioAge}`,
      description: `Реальный возраст: ${realAge}. Биологический возраст тела: ${bioAge}. ${ageStatus(bioAge, race)}. ${race.ability} Слабость: ${race.weakness}`,
      revealed: false,
      used: false,
      raceId: race.id,
      age: realAge,
      bioAge
    };
  }

  const age = randomInt(18, race.maxAge);
  let extra = "";

  if (race.id === "triclops") {
    const [eye, desc] = pick(eyePowers);
    extra = ` Третий глаз: ${eye}. ${desc}`;
  }

  if (race.id === "saint") {
    const [phase, desc] = saintPhase();
    extra = ` Фаза: ${phase}. ${desc}`;
  }

  if (race.id === "beastfolk") {
    const beast = pick(beastTypes);
    const beastPercent = randomInt(20, 90);
    const humanPercent = 100 - beastPercent;
    extra = ` Тип: ${beast} на ${beastPercent}% / человек на ${humanPercent}%. Чем больше зверя, тем больше инстинктов и силы, но меньше контроля.`;
  }

  if (race.id === "mosquito") {
    const sex = Math.random() < 0.5 ? "женщина-комар" : "мужчина-комар";
    extra = sex === "женщина-комар"
      ? " Пол: женщина-комар. Может временно высасывать баффы врагов."
      : " Пол: мужчина-комар. Слабее, но очень назойливый и мешает речи.";
  }

  return {
    type: "Раса и возраст",
    title: `${race.name}: ${age} лет`,
    description: `${ageStatus(age, race)}. ${race.ability} Слабость: ${race.weakness}${extra}`,
    revealed: false,
    used: false,
    raceId: race.id,
    age
  };
}

