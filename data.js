export function generateBunker(settings = {}) {
  const base = pick(bunkerSizes);
  const [minCap, maxCap] = base[2];
  const capacity = Number(settings.bunkerSeats) || randomInt(minCap, maxCap);
  const maxPlayers = Number(settings.maxPlayers) || Math.max(capacity + 2, 8);
  const roomCount = Math.min(8, randomInt(4, 7));
  const rooms = Array.from({ length: roomCount }, () => pick(bunkerRooms));
  const items = Array.from({ length: randomInt(5, 8) }, () => pick(bunkerItems));
  const defects = Array.from({ length: randomInt(2, 4) }, () => pick(bunkerProblems));
  return {
    title: `${base[0]} бункер на ${capacity} мест`,
    size: base[0],
    description: base[1],
    capacity,
    maxPlayers,
    rooms: [...new Set(rooms)],
    items: [...new Set(items)],
    defects: [...new Set(defects)],
    text: `${base[0]} бункер. Вместимость: ${capacity}/${maxPlayers}. ${base[1]}. Комнаты: ${[...new Set(rooms)].join(", ")}. Предметы: ${[...new Set(items)].join(", ")}. Проблемы: ${[...new Set(defects)].join(", ")}.`
  };
}

export function generateRoundEvent(round = 1, mode = "meme", settings = {}) {
  if (round <= 3) return noRoundEvent(round, "События отключены до конца третьего круга раскрытия.");

  const eventChance = clampPercent(settings?.eventChance, 30);
  const eventAppears = Math.random() * 100 < eventChance;
  if (!eventAppears) return noRoundEvent(round, `Шанс события не сработал: ${100 - eventChance}% тишины победили ${eventChance}% хаоса.`);

  let available = roundEvents.filter((event) => {
    if (!event.modes) return true;
    if (mode === "chaos") return event.modes.includes("chaos") || event.modes.includes("meme") || event.modes.includes("adult");
    return event.modes.includes(mode);
  });
  if (mode === "normal") available = available.filter((event) => !event.modes || event.modes.includes("normal"));
  if (!available.length) available = roundEvents.filter((event) => !event.modes);

  const event = weightedEventPick(available, settings);
  return {
    ...event,
    id: `${event.effectType}_${Date.now()}_${Math.random().toString(16).slice(2, 7)}`,
    round,
    text: `Круг ${round}: ${event.title}. ${event.description} ${event.impact}`
  };
}
