function poolByMode(list, mode = "meme", normalLimit = null, chaosExtra = [], adultExtra = []) {
  const cleanMode = mode || "meme";
  const limit = normalLimit ?? Math.max(6, Math.ceil(list.length * 0.62));
  if (cleanMode === "normal") return list.slice(0, limit);
  if (cleanMode === "adult") return list.concat(adultExtra);
  if (cleanMode === "chaos") return list.concat(chaosExtra).concat(adultExtra);
  return list;
}

function pickByMode(list, mode, normalLimit = null, chaosExtra = [], adultExtra = []) {
  return pick(poolByMode(list, mode, normalLimit, chaosExtra, adultExtra));
}

