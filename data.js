function poolByMode(list, mode = "meme", normalLimit = null, chaosExtra = []) {
  const cleanMode = mode || "meme";
  const limit = normalLimit ?? Math.max(6, Math.ceil(list.length * 0.62));
  if (cleanMode === "normal") return list.slice(0, limit);
  if (cleanMode === "chaos") return list.concat(chaosExtra);
  return list;
}

function pickByMode(list, mode, normalLimit = null, chaosExtra = []) {
  return pick(poolByMode(list, mode, normalLimit, chaosExtra));
}

export function randomBaggageCard(mode = "meme") {
  return makeCard("Багаж", pickByMode(baggage, mode, 20, chaosBaggage));
}

