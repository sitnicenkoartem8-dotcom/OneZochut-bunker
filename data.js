const defaultEventWeights = { common: 85, rare: 12, super_rare: 3, legendary: 0 };

function clampPercent(value, fallback = 0) {
  const n = Number(value);
  if (!Number.isFinite(n)) return fallback;
  return Math.max(0, Math.min(100, n));
}

function normalizeEventWeights(settings = {}) {
  const raw = settings?.eventWeights || defaultEventWeights;
  const weights = {
    common: clampPercent(raw.common, defaultEventWeights.common),
    rare: clampPercent(raw.rare, defaultEventWeights.rare),
    super_rare: clampPercent(raw.super_rare, defaultEventWeights.super_rare),
    legendary: clampPercent(raw.legendary, defaultEventWeights.legendary)
  };
  const total = Object.values(weights).reduce((sum, value) => sum + value, 0);
  return total > 0 ? weights : { ...defaultEventWeights };
}

function noRoundEvent(round, reason = "В этом круге событие не появилось") {
  return {
    id: `no_event_${round}_${Date.now()}_${Math.random().toString(16).slice(2, 7)}`,
    title: round <= 3 ? "Первые три круга без событий" : "Тихий круг",
    rarity: "none",
    effectType: "none",
    isNoEvent: true,
    round,
    description: round <= 3
      ? "Первые три круга игра идёт без событий: игроки спокойно раскрывают карты, спорят и собирают аргументы."
      : reason,
    impact: "Реального эффекта нет. Совет продолжает игру по обычным правилам.",
    text: `Круг ${round}: события нет. ${reason}`
  };
}

function weightedEventPick(events, settings = {}) {
  const weights = normalizeEventWeights(settings);
  const order = ["common", "rare", "super_rare", "legendary"];
  const total = order.reduce((sum, rarity) => sum + (weights[rarity] || 0), 0) || 100;
  let roll = Math.random() * total;
  let rarity = "common";
  for (const item of order) {
    roll -= weights[item] || 0;
    if (roll <= 0) {
      rarity = item;
      break;
    }
  }
  const pool = events.filter((event) => event.rarity === rarity);
  if (pool.length) return pick(pool);
  for (const fallbackRarity of ["common", "rare", "super_rare", "legendary"]) {
    const fallback = events.filter((event) => event.rarity === fallbackRarity);
    if (fallback.length) return pick(fallback);
  }
  return pick(events);
}

export function generateStory(mode = "meme") {
  const start = pick(apocalypsePoolByMode(mode));
  const place = pick(bunkerPlaces);
  const problem = pick(bunkerProblems);
  const goal = pick(winConditions);
  const title = start[0];
  const duration = storyDuration(title);
  const afterExit = storyAfterExit(title);
  const survivalFocus = storySurvivalFocus(title);
  return {
    title,
    intro: start[1],
    outside: start[2],
    place,
    problem,
    goal,
    duration,
    afterExit,
    survivalFocus,
    text: `${title}. ${start[1]} Почему нужно прятаться: ${start[2]} Срок бункера: ${duration}. После выхода: ${afterExit}. Бункер находится ${place}. Главная проблема бункера: ${problem}. Цель выживших: ${goal}. Кого ценить: ${survivalFocus.join(", ")}.`
  };
}

